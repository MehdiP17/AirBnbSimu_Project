DROP TABLE IF EXISTS loyers, reviews, listing_snapshots, listing_amenities,
                     amenities, listings, quartiers, arrondissements, mois CASCADE;
                     
CREATE TABLE "mois" (
  "mois" int PRIMARY KEY,
  "nom_mois" varchar(20)
);

CREATE TABLE "arrondissements" (
  "numero" int PRIMARY KEY,
  "nom" varchar(50)
);

CREATE TABLE "quartiers" (
  "id_quartier" int PRIMARY KEY,
  "nom_quartier" varchar,
  "arrondissement" int,
  "code_grand_quartier" int,
  "latitude" float8,
  "longitude" float8,
  "geoshape" jsonb
);

CREATE TABLE "listings" (
  "listing_id" bigint PRIMARY KEY,
  "arrondissement" int,
  "room_type" varchar,
  "accommodates" int,
  "bedrooms" int,
  "bathrooms" numeric(2,1),
  "pieces" int,
  "latitude" float8,
  "longitude" float8,
  "n_amenities" int
);

CREATE TABLE "amenities" (
  "amenity_id" int PRIMARY KEY,
  "nom" varchar
);

CREATE TABLE "listing_amenities" (
  "listing_id" bigint,
  "amenity_id" int,
  PRIMARY KEY ("listing_id", "amenity_id")
);

CREATE TABLE "listing_snapshots" (
  "listing_id" bigint,
  "snapshot_date" date,
  "releve" date,
  "price" numeric(10,2),
  "avec_taxes" boolean,
  "checkin_month" int,
  "days_before_checkin" int,
  "test_nights" int,
  "minimum_nights" int,
  "number_of_reviews_ltm" int,
  "nuits_an" int,
  PRIMARY KEY ("listing_id", "snapshot_date")
);

CREATE TABLE "reviews" (
  "review_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "listing_id" bigint,
  "date" date,
  "mois" int
);

CREATE TABLE "loyers" (
  "annee" int,
  "id_quartier" int,
  "pieces" int,
  "epoque" varchar,
  "meuble" bool,
  "loyer_ref" numeric(10,2),
  "loyer_max" numeric(10,2),
  "loyer_min" numeric(10,2),
  PRIMARY KEY ("annee", "id_quartier", "pieces", "epoque", "meuble")
);

COMMENT ON TABLE "mois" IS '12 lignes';

COMMENT ON TABLE "arrondissements" IS '20 lignes';

COMMENT ON TABLE "quartiers" IS '80 lignes';

COMMENT ON COLUMN "amenities"."nom" IS 'wifi, lave vaisselle, etc...';

COMMENT ON TABLE "listing_amenities" IS 'Table pont : relie listings et amenities';

ALTER TABLE "quartiers" ADD FOREIGN KEY ("arrondissement") REFERENCES "arrondissements" ("numero") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "listings" ADD FOREIGN KEY ("arrondissement") REFERENCES "arrondissements" ("numero") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "listing_amenities" ADD FOREIGN KEY ("listing_id") REFERENCES "listings" ("listing_id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "listing_amenities" ADD FOREIGN KEY ("amenity_id") REFERENCES "amenities" ("amenity_id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "listing_snapshots" ADD FOREIGN KEY ("listing_id") REFERENCES "listings" ("listing_id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "listing_snapshots" ADD FOREIGN KEY ("checkin_month") REFERENCES "mois" ("mois") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "reviews" ADD FOREIGN KEY ("listing_id") REFERENCES "listings" ("listing_id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "reviews" ADD FOREIGN KEY ("mois") REFERENCES "mois" ("mois") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "loyers" ADD FOREIGN KEY ("id_quartier") REFERENCES "quartiers" ("id_quartier") DEFERRABLE INITIALLY IMMEDIATE;