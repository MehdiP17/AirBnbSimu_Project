DROP TABLE IF EXISTS rent, reviews, listing_snapshots, listing_amenities,
                     amenities, listings, neighborhoods, disctricts, months CASCADE;
                     
CREATE TABLE "months" (
  "month" int PRIMARY KEY,
  "month_name" varchar(20)
);

CREATE TABLE "districts" (
  "number" int PRIMARY KEY,
  "name" varchar(50)
);

CREATE TABLE "neighborhoods" (
  "neighborhood_id" int PRIMARY KEY,
  "neighborhood_name" varchar,
  "district" int,
  "major_district_code" int,
  "latitude" float8,
  "longitude" float8,
  "geoshape" jsonb
);

CREATE TABLE "listings" (
  "listing_id" bigint PRIMARY KEY,
  "district" int,
  "room_type" varchar,
  "accommodates" int,
  "bedrooms" int,
  "bathrooms" numeric(2,1),
  "rooms" int,
  "latitude" float8,
  "longitude" float8,
  "n_amenities" int
);

CREATE TABLE "amenities" (
  "amenity_id" int PRIMARY KEY,
  "name" varchar
);

CREATE TABLE "listing_amenities" (
  "listing_id" bigint,
  "amenity_id" int,
  PRIMARY KEY ("listing_id", "amenity_id")
);

CREATE TABLE "listing_snapshots" (
  "listing_id" bigint,
  "snapshot_date" date,
  "statement" date,
  "price" numeric(10,2),
  "with_taxes" boolean,
  "checkin_month" int,
  "days_before_checkin" int,
  "test_nights" int,
  "minimum_nights" int,
  "number_of_reviews_ltm" int,
  "nights_an" int,
  PRIMARY KEY ("listing_id", "snapshot_date")
);

CREATE TABLE "reviews" (
  "review_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "listing_id" bigint,
  "date" date,
  "month" int
);

CREATE TABLE "rent" (
  "year" int,
  "neighborhood_id" int,
  "rooms" int,
  "construction_period" varchar,
  "furnished" bool,
  "ref_rent" numeric(10,2),
  "max_rent" numeric(10,2),
  "min_rent" numeric(10,2),
  PRIMARY KEY ("year", "neighborhood_id", "rooms", "construction_period", "furnished")
);

COMMENT ON TABLE "months" IS '12 lines';

COMMENT ON TABLE "districts" IS '20 lines';

COMMENT ON TABLE "neighborhoods" IS '80 lines';

COMMENT ON COLUMN "amenities"."name" IS 'wifi, lave vaisselle, etc...';

COMMENT ON TABLE "listing_amenities" IS 'Table pont : relie listings et amenities';

ALTER TABLE "neighborhoods" ADD FOREIGN KEY ("district") REFERENCES "districts" ("number") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "listings" ADD FOREIGN KEY ("district") REFERENCES "districts" ("number") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "listing_amenities" ADD FOREIGN KEY ("listing_id") REFERENCES "listings" ("listing_id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "listing_amenities" ADD FOREIGN KEY ("amenity_id") REFERENCES "amenities" ("amenity_id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "listing_snapshots" ADD FOREIGN KEY ("listing_id") REFERENCES "listings" ("listing_id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "listing_snapshots" ADD FOREIGN KEY ("checkin_month") REFERENCES "months" ("month") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "reviews" ADD FOREIGN KEY ("listing_id") REFERENCES "listings" ("listing_id") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "reviews" ADD FOREIGN KEY ("month") REFERENCES "months" ("month") DEFERRABLE INITIALLY IMMEDIATE;

ALTER TABLE "rent" ADD FOREIGN KEY ("neighborhood_id") REFERENCES "neighborhoods" ("neighborhood_id") DEFERRABLE INITIALLY IMMEDIATE;